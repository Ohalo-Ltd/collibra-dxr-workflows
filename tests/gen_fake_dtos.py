#!/usr/bin/env python3
"""Generate the fake Collibra classes the offline Groovy tests compile against.

Every Collibra class the pack's scripts name (fully qualified, or in an import)
gets a file under tests/groovy/<package path>/<Class>.groovy:

  - a request DTO with a Builder in Collibra's Javadoc → a class whose
    builder() accepts exactly the builder methods the Javadoc lists, so a
    misspelt or removed builder method fails a test the way it fails in
    Collibra (MissingMethodException at runtime);
  - an enum → a Groovy enum with the Javadoc's constants;
  - anything else → an empty placeholder class (only Configure uses these, and
    the offline tests do not run Configure).

WorkflowException (workflow API) is written by hand: tests read its title and
user message.

The Javadoc lives in the harness (docs/ohalo.collibra.com_javadoc/). Re-run
after a Collibra upgrade or when a script starts using a new class, and commit
the output:

    python packs/dxr-workflows/tests/gen_fake_dtos.py
"""
from __future__ import annotations

import os
import re
import sys
from pathlib import Path

PACK = Path(__file__).resolve().parents[1]
HARNESS = Path(os.environ.get("HARNESS_ROOT") or PACK.parents[1]).resolve()
JAVADOC = HARNESS / "docs" / "ohalo.collibra.com_javadoc" / "dgc-core-api-32.1.43-javadoc.md"
OUT = PACK / "tests" / "groovy"

FQCN_RE = re.compile(r"\b(com\.collibra\.[a-z][\w.]*)\.([A-Z]\w*)\b")
HAND_WRITTEN = {("com.collibra.dgc.workflow.api.exception", "WorkflowException")}
HEADER = "// GENERATED by tests/gen_fake_dtos.py from Collibra's Javadoc (32.1.43). Do not edit.\n"


def referenced_classes() -> set[tuple[str, str]]:
    found: set[tuple[str, str]] = set()
    for path in [*PACK.glob("shared/*.groovy"), *PACK.glob("workflows/*/scripts/**/*.groovy")]:
        found.update(FQCN_RE.findall(path.read_text(encoding="utf-8")))
    return found


def javadoc_sections(text: str) -> dict[tuple[str, str], str]:
    """(package, section title) → section body, for every '## Title' section."""
    out: dict[tuple[str, str], str] = {}
    for chunk in re.split(r"^## ", text, flags=re.MULTILINE)[1:]:
        title, _, body = chunk.partition("\n")
        m = re.search(r"\*\*Package:\*\* ([\w.]+)", body)
        if m:
            out[(m.group(1), title.strip())] = body
    return out


def builder_methods(section: str, cls: str) -> list[str]:
    names = re.findall(rf"^public {re.escape(cls)}\.Builder (\w+)\(", section, flags=re.MULTILINE)
    return sorted(set(names) - {"but"})


def enum_constants(section: str) -> list[str]:
    details = section.split("### Enum Constant Details", 1)
    return re.findall(r"^#### ([A-Z][A-Z0-9_]*)\s*$", details[1], flags=re.MULTILINE) if len(details) == 2 else []


def render(pkg: str, cls: str, sections: dict) -> str:
    builder = sections.get((pkg, f"{cls}.Builder"))
    if builder is not None:
        methods = builder_methods(builder, cls)
        allowed = ", ".join(f"'{m}'" for m in methods)
        return (f"{HEADER}package {pkg}\n\n"
                f"class {cls} extends fake.Dto {{\n"
                f"    static final Set<String> BUILDER_METHODS = [{allowed}] as Set\n"
                f"    static fake.DtoBuilder builder() {{ new fake.DtoBuilder({cls}, BUILDER_METHODS) }}\n"
                f"}}\n")
    own = sections.get((pkg, cls), "")
    if re.search(rf"public enum {re.escape(cls)}\b", own):
        constants = enum_constants(own)
        if not constants:
            raise SystemExit(f"{pkg}.{cls}: an enum with no constants in the Javadoc")
        return f"{HEADER}package {pkg}\n\nenum {cls} {{ {', '.join(constants)} }}\n"
    return (f"{HEADER}package {pkg}\n\n"
            f"// Not modelled: only scripts the offline tests never run use it.\n"
            f"class {cls} extends fake.Dto {{ }}\n")


def main() -> None:
    if not JAVADOC.exists():
        raise SystemExit(f"Javadoc not found: {JAVADOC} (set HARNESS_ROOT)")
    sections = javadoc_sections(JAVADOC.read_text(encoding="utf-8"))
    written = []
    for pkg, cls in sorted(referenced_classes() - HAND_WRITTEN):
        target = OUT.joinpath(*pkg.split("."), f"{cls}.groovy")
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(render(pkg, cls, sections), encoding="utf-8")
        written.append(f"{pkg}.{cls}")
    print(f"{len(written)} fake class(es) written under {OUT.relative_to(PACK)}")


if __name__ == "__main__":
    sys.exit(main())
